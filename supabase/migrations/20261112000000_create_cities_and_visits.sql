create table public.cities (
    id bigint generated by default as identity primary key,
    country_id bigint not null references public.countries(id),
    name text not null,
    name_ja text not null,
    latitude double precision not null,
    longitude double precision not null,
    unique (country_id, name)
);

create index cities_country_id_idx on public.cities (country_id);
alter table public.cities enable row level security;
revoke all on table public.cities from anon, authenticated;
grant select on table public.cities to authenticated;
create policy "Authenticated users can read cities"
    on public.cities for select to authenticated using (true);

create table public.visits (
    id uuid primary key default gen_random_uuid(),
    user_id uuid not null references auth.users(id) on delete cascade,
    city_id bigint not null references public.cities(id) on delete no action,
    visited_date date not null,
    title text not null,
    memo text,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

create index visits_user_date_idx on public.visits (user_id, visited_date desc);
create index visits_user_city_date_idx on public.visits (user_id, city_id, visited_date desc);

create function public.set_visit_updated_at()
returns trigger language plpgsql set search_path = '' as $$
begin
    new.updated_at = now();
    return new;
end;
$$;

create trigger visits_set_updated_at before update on public.visits
for each row execute function public.set_visit_updated_at();

alter table public.visits enable row level security;
revoke all on table public.visits from anon, authenticated;
grant select on table public.visits to authenticated;
create policy "Users can read their own visits"
    on public.visits for select to authenticated
    using ((select auth.uid()) = user_id);
